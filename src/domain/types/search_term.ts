/**
 * SIEVE Domain Core: Search Term Entity & Platform Match Types
 *
 * Defines search term entities and platform targeting match types.
 * All financial metrics (spend, CPC, revenue) utilize integer micro-units.
 */

import type {
  CurrencyMicros,
  ClickCount,
  ImpressionCount,
  QueryString,
  CampaignId,
  AdGroupId,
} from './primitives.ts';

/**
 * Platform match type variants discriminating ad network keyword targeting precision.
 * - `EXACT`: Targeted keyword matches user query verbatim or close syntactic variant.
 * - `PHRASE`: Targeted keyword sequence is preserved within user query.
 * - `BROAD`: Algorithmic semantic matching determined by ad auction engine.
 */
export type PlatformMatchType = 'EXACT' | 'PHRASE' | 'BROAD';

/**
 * Immutable search term entity record representing query-level auction performance metrics.
 */
export interface SearchTermRecord {
  /** The unnormalized search term string as delivered by the search advertising network. */
  readonly rawQuery: QueryString;
  /** Normalized lowercase, punctuation-stripped search term representation for aggregation. */
  readonly normalizedQuery: QueryString;
  /** Human-readable name of the advertising campaign containing the search query auction. */
  readonly campaignName: string;
  /** Human-readable name of the ad group containing the matched keyword or criteria. */
  readonly adGroupName: string;
  /** Targeted platform match type ('EXACT' | 'PHRASE' | 'BROAD'). */
  readonly matchType: PlatformMatchType;
  /** Total ad impressions delivered on search result pages. */
  readonly impressions: ImpressionCount;
  /** Total user clicks generated by this search term. */
  readonly clicks: ClickCount;
  /** Total advertising expenditure represented in integer micro-units. */
  readonly spendMicros: CurrencyMicros;
  /** Attributed conversion count, supporting fractional attribution models (e.g., 0.5, 1.25). */
  readonly conversions: number;
  /** Total conversion value / revenue recorded in integer micro-units. */
  readonly revenueMicros: CurrencyMicros;
  /** Calculated average cost-per-click represented in integer micro-units. */
  readonly averageCpcMicros: CurrencyMicros;
  /** Optional campaign identifier for relational joining. */
  readonly campaignId?: CampaignId;
  /** Optional ad group identifier for relational joining. */
  readonly adGroupId?: AdGroupId;
  /** Flag indicating whether this search term collides with safe-list converting traffic. */
  readonly hasCollision?: boolean;
}

/**
 * Aggregated metrics summary for a partitioned collection of search terms.
 */
export interface SearchTermMetricsSummary {
  /** Total search term record count. */
  readonly recordCount: number;
  /** Sum of all ad impressions across terms. */
  readonly totalImpressions: ImpressionCount;
  /** Sum of all clicks across terms. */
  readonly totalClicks: ClickCount;
  /** Sum of all expenditure across terms in integer micro-units. */
  readonly totalSpendMicros: CurrencyMicros;
  /** Sum of all attributed conversions across terms. */
  readonly totalConversions: number;
  /** Sum of all revenue across terms in integer micro-units. */
  readonly totalRevenueMicros: CurrencyMicros;
  /** Weighted average cost-per-click across terms in integer micro-units. */
  readonly averageCpcMicros: CurrencyMicros;
}

/**
 * Filter criteria for filtering and partitioning collections of search term records.
 */
export interface SearchTermFilterCriteria {
  /** Target platform match types to include. */
  readonly matchTypes?: readonly PlatformMatchType[];
  /** Minimum spend threshold in integer micro-units. */
  readonly minSpendMicros?: CurrencyMicros;
  /** Minimum click count threshold. */
  readonly minClicks?: ClickCount;
  /** Minimum impression count threshold. */
  readonly minImpressions?: ImpressionCount;
  /** Optional campaign name filter. */
  readonly campaignName?: string;
  /** Optional ad group name filter. */
  readonly adGroupName?: string;
}
