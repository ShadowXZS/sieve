/**
 * SIEVE Domain Core: Safety Shield & Negative Exclusion Rules
 *
 * Implements deterministic safety rules to protect converting search terms
 * from collateral damage when deploying negative keyword exclusions.
 * All monetary estimates use integer micro-units.
 */

import type {
  CurrencyMicros,
  QueryString,
  CampaignId,
  AdGroupId,
} from './primitives.ts';
import type { PlatformMatchType } from './search_term.ts';

/**
 * Collision verdict evaluating negative keyword safety against converting queries.
 * - `SAFE_LIST_CONVERSION`: Exact match with proven historical conversions. Negative exclusion blocked to prevent revenue loss.
 * - `EXACT_BRACKET_LOCK`: Broad/phrase exclusion would collide with converting traffic; forced to exact bracket [term] negative.
 * - `SAFE_EXCLUSION`: Zero collision detected with converting traffic. Safe for broad or phrase negative exclusion.
 */
export type CollisionVerdict =
  | 'SAFE_LIST_CONVERSION'
  | 'EXACT_BRACKET_LOCK'
  | 'SAFE_EXCLUSION';

/**
 * Target deployment scope level for negative keyword rule enforcement.
 * - `ACCOUNT`: Deployed globally to account-level negative keyword list.
 * - `CAMPAIGN`: Deployed specifically to target campaign scope.
 * - `AD_GROUP`: Deployed strictly to target ad group scope.
 */
export type ExclusionTargetLevel = 'ACCOUNT' | 'CAMPAIGN' | 'AD_GROUP';

/**
 * Formal negative keyword exclusion rule generated by the SIEVE safety shield.
 */
export interface NegativeExclusionRule {
  /** The candidate search term or token recommended for negative exclusion. */
  readonly candidateTerm: QueryString;
  /** Recommended platform match type ('EXACT' | 'PHRASE' | 'BROAD'). */
  readonly recommendedMatchType: PlatformMatchType;
  /** Hierarchical deployment scope level within the advertising account hierarchy. */
  readonly targetLevel: ExclusionTargetLevel;
  /** Estimated marginal financial waste eliminated by this rule in integer micro-units. */
  readonly marginalWasteMicros: CurrencyMicros;
  /** Statistical or Bayesian confidence score for the recommendation (0.0 to 1.0). */
  readonly confidenceScore: number;
  /** Safety collision verdict dictating match type restrictions. */
  readonly verdict: CollisionVerdict;
  /** Optional campaign identifier when target level is CAMPAIGN or AD_GROUP. */
  readonly campaignId?: CampaignId;
  /** Optional ad group identifier when target level is AD_GROUP. */
  readonly adGroupId?: AdGroupId;
  /** Deterministic SHA-256 fingerprint of normalized rule for idempotent storage. */
  readonly ruleFingerprint: string;
  /** List of converting terms that would collide if match type were unconstrained. */
  readonly collidingSafeTerms?: readonly QueryString[];
}

/**
 * Safe-list conversion entity protecting proven converting queries from negative exclusion.
 */
export interface SafeListTerm {
  /** Normalized search query string protected from negative exclusion. */
  readonly query: QueryString;
  /** Historical conversion volume attributed to this query. */
  readonly conversions: number;
  /** Historical conversion value secured by this query in integer micro-units. */
  readonly securedRevenueMicros: CurrencyMicros;
  /** Epoch timestamp in milliseconds when this term was added to the safe-list. */
  readonly createdAtMs: number;
}

/**
 * Detailed evaluation outcome when testing a candidate negative keyword against the safe-list.
 */
export interface CollisionEvaluationResult {
  /** Candidate query string tested. */
  readonly candidate: QueryString;
  /** Safety collision verdict. */
  readonly verdict: CollisionVerdict;
  /** Enforced match type recommendation. */
  readonly recommendedMatchType: PlatformMatchType;
  /** Conflicting safe-list terms that triggered collision logic (if any). */
  readonly conflictingSafeTerms: readonly QueryString[];
}
