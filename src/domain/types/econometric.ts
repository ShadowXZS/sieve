/**
 * SIEVE Domain Core: Econometric Modeling & Bid Elasticity Spectrum
 *
 * Models the econometric bid elasticity spectrum, non-linear diminishing returns,
 * and convex capital reallocation yield.
 * All monetary values use integer micro-units to guarantee financial precision.
 */

import type { CurrencyMicros } from './primitives.ts';

/**
 * Econometric elasticity zone classifying marginal bid efficiency.
 * - `PROFITABLE`: Bids operate below optimal ceiling where marginal revenue exceeds marginal cost.
 * - `DIMINISHING`: Bids operate near boundary where conversion volume gains exhibit diminishing returns.
 * - `DEAD_ZONE`: Bids operate beyond optimal ceiling, incurring CPA inflation without incremental conversion yield.
 */
export type ElasticityZone = 'PROFITABLE' | 'DIMINISHING' | 'DEAD_ZONE';

/**
 * Bid elasticity spectrum modeling cost boundary dynamics between converting and non-converting auctions.
 */
export interface BidElasticitySpectrum {
  /** Median cost-per-click for queries generating at least one conversion in integer micro-units. */
  readonly convertingMedianCpcMicros: CurrencyMicros;
  /** Median cost-per-click for non-converting queries in integer micro-units. */
  readonly nonConvertingMedianCpcMicros: CurrencyMicros;
  /** Difference between converting median CPC and non-converting median CPC in integer micro-units. */
  readonly cpcBoundaryDeltaMicros: CurrencyMicros;
  /** Mathematically optimal bid ceiling to maximize conversions while mitigating dead-zone spend in integer micro-units. */
  readonly optimalBidCeilingMicros: CurrencyMicros;
  /** Classified elasticity zone based on current account bidding behavior. */
  readonly elasticityZone: ElasticityZone;
  /** Maximum observed CPC across analyzed search queries in integer micro-units. */
  readonly maxObservedCpcMicros?: CurrencyMicros;
}

/**
 * Convex yield model projecting incremental conversion gains from reallocating eliminated waste.
 */
export interface ConvexReallocationYield {
  /** Historical baseline conversion count before negative keyword optimization. */
  readonly baselineConversions: number;
  /** Projected total conversions after reallocating recovered waste into top-performing queries. */
  readonly projectedConversions: number;
  /**
   * Diminishing returns elasticity coefficient (standard domain parameter: 0.70 to 0.85).
   * Models non-linear auction saturation according to the Cobb-Douglas production function.
   */
  readonly elasticityCoefficient: number;
  /** Target cost-per-acquisition benchmark in integer micro-units. */
  readonly targetCpaMicros: CurrencyMicros;
  /** Projected Return On Ad Spend (ROAS) lift percentage (e.g., 0.22 represents 22% improvement). */
  readonly projectedRoasLift: number;
  /** Projected incremental conversions generated by capital reallocation. */
  readonly incrementalConversions?: number;
  /** Annualized monetary recovery yield in integer micro-units. */
  readonly annualizedRecoveryMicros?: CurrencyMicros;
  /** Efficiency multiplier ratio comparing projected yield over baseline spend. */
  readonly efficiencyMultiplier?: number;
}

/**
 * Four-tier spend waterfall categorization for executive capital governance.
 */
export interface SpendWaterfallSpectrum {
  /** Total analyzed account expenditure in integer micro-units. */
  readonly totalSpendMicros: CurrencyMicros;
  /** Tier 1: Confirmed waste bleed (zero-conversion high-spend terms) in integer micro-units. */
  readonly wasteSpendMicros: CurrencyMicros;
  /** Tier 2: Safe-list protected spend (confirmed converting terms) in integer micro-units. */
  readonly securedSpendMicros: CurrencyMicros;
  /** Tier 3: Exploratory risk spend (sub-sample or high CPC auction queries) in integer micro-units. */
  readonly exploratorySpendMicros: CurrencyMicros;
}
