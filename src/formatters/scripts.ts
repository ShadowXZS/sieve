/**
 * Google Ads Script Generator (Phase 5)
 *
 * Synthesizes 100% self-contained Google Ads JavaScript scripts.
 * Adheres strictly to the Google Ads Scripts (AdsApp) runtime execution environment
 * with zero external dependencies, HTTP requests, or remote CDN calls.
 */

import type { PersistedNegativeKeyword } from '../workers/protocol.ts';
import { normalizeGoogleAdsKeyword } from './syntax.ts';

export interface GoogleAdsScriptOptions {
  campaignNames?: string[];
  batchSize?: number;
  applyToAllCampaigns?: boolean;
  scriptName?: string;
}

/**
 * Generates an automated, self-contained Google Ads Script.
 */
export function generateGoogleAdsScript(
  keywords: PersistedNegativeKeyword[],
  options: GoogleAdsScriptOptions = {}
): string {
  const batchSize = options.batchSize || 100;
  const scriptName = options.scriptName || 'Sieve_Automated_Negative_Exclusions';

  // Group keywords with their normalized forms
  const keywordData = keywords.map((kw) => {
    const norm = normalizeGoogleAdsKeyword(kw.keyword, kw.matchType, kw.hasCollision);
    return {
      keyword: norm.keywordText,
      formattedRule: norm.formattedText,
      matchType: norm.criterionType.replace('Negative ', '').toUpperCase(), // EXACT, PHRASE, BROAD
      campaign: kw.scope?.campaign || null,
      adGroup: kw.scope?.adGroup || null,
    };
  });

  const payloadJson = JSON.stringify(keywordData, null, 2);

  return `/**
 * ${scriptName}
 *
 * Generated by Sieve Core - Bayesian Search Term Filter.
 * 100% Self-Contained Google Ads JavaScript Script.
 * Runs directly inside Google Ads Scripts environment without external dependencies.
 */

function main() {
  Logger.log('Starting Sieve Negative Keyword Sync...');

  var RULES = ${payloadJson};
  var BATCH_SIZE = ${batchSize};
  var totalProcessed = 0;
  var errorsCount = 0;

  var campaignRules = {};
  var adGroupRules = {};
  var universalRules = [];

  for (var i = 0; i < RULES.length; i++) {
    var rule = RULES[i];
    if (rule.campaign && rule.adGroup) {
      var key = rule.campaign + '///' + rule.adGroup;
      if (!adGroupRules[key]) adGroupRules[key] = [];
      adGroupRules[key].push(rule.formattedRule);
    } else if (rule.campaign) {
      if (!campaignRules[rule.campaign]) campaignRules[rule.campaign] = [];
      campaignRules[rule.campaign].push(rule.formattedRule);
    } else {
      universalRules.push(rule.formattedRule);
    }
  }

  // 1. Process Campaign-Level Rules
  for (var campName in campaignRules) {
    if (!Object.prototype.hasOwnProperty.call(campaignRules, campName)) continue;
    var rulesForCamp = campaignRules[campName];
    try {
      var campIter = AdsApp.campaigns()
        .withCondition('Name = "' + escapeString(campName) + '"')
        .get();

      if (campIter.hasNext()) {
        var campaign = campIter.next();
        for (var c = 0; c < rulesForCamp.length; c++) {
          campaign.createNegativeKeyword(rulesForCamp[c]);
          totalProcessed++;
        }
        Logger.log('Added ' + rulesForCamp.length + ' negative rules to Campaign: ' + campName);
      } else {
        Logger.log('Campaign not found: ' + campName);
      }
    } catch (err) {
      Logger.log('Error applying rules to Campaign ' + campName + ': ' + err);
      errorsCount++;
    }
  }

  // 2. Process AdGroup-Level Rules
  for (var agKey in adGroupRules) {
    if (!Object.prototype.hasOwnProperty.call(adGroupRules, agKey)) continue;
    var parts = agKey.split('///');
    var targetCamp = parts[0];
    var targetAg = parts[1];
    var rulesForAg = adGroupRules[agKey];

    try {
      var agIter = AdsApp.adGroups()
        .withCondition('CampaignName = "' + escapeString(targetCamp) + '"')
        .withCondition('Name = "' + escapeString(targetAg) + '"')
        .get();

      if (agIter.hasNext()) {
        var adGroup = agIter.next();
        for (var a = 0; a < rulesForAg.length; a++) {
          adGroup.createNegativeKeyword(rulesForAg[a]);
          totalProcessed++;
        }
        Logger.log('Added ' + rulesForAg.length + ' negative rules to AdGroup: ' + targetAg);
      }
    } catch (err) {
      Logger.log('Error applying rules to AdGroup ' + targetAg + ': ' + err);
      errorsCount++;
    }
  }

  // 3. Process Universal Rules across all active campaigns if any
  if (universalRules.length > 0) {
    Logger.log('Applying ' + universalRules.length + ' universal rules to all active campaigns...');
    try {
      var allCamps = AdsApp.campaigns()
        .withCondition('Status = ENABLED')
        .get();

      while (allCamps.hasNext()) {
        var activeCamp = allCamps.next();
        for (var u = 0; u < universalRules.length; u++) {
          activeCamp.createNegativeKeyword(universalRules[u]);
          totalProcessed++;
        }
      }
    } catch (err) {
      Logger.log('Error applying universal rules: ' + err);
      errorsCount++;
    }
  }

  Logger.log('Completed Sieve Exclusion Sync. Total operations: ' + totalProcessed + ', Errors: ' + errorsCount);
}

function escapeString(str) {
  return str.replace(/"/g, '\\\\"');
}
`;
}

